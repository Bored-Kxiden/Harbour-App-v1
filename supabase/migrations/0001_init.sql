-- auth.uid() is wrapped in a scalar subquery throughout so the planner runs it
-- once per statement rather than once per row.

-- profiles: yours to write; a linked person may read (the views narrow what
-- that means in practice, and nothing sensitive lives here anyway).
create policy "read own profile"    on profiles for select
  using ((select auth.uid()) = id or harbour_linked((select auth.uid()), id));
create policy "write own profile"   on profiles for update
  using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
create policy "insert own profile"  on profiles for insert
  with check ((select auth.uid()) = id);

create policy "own settings" on user_settings for all
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

create policy "own contacts" on contacts for all
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

-- The day: yours to write, and readable by a linked person only when you have
-- turned sharing on. shared_busy is what they actually select from.
create policy "own busy blocks" on busy_blocks for all
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "linked can read busy times" on busy_blocks for select
  using (
    harbour_linked((select auth.uid()), user_id)
    and exists (select 1 from user_settings s where s.user_id = busy_blocks.user_id and s.sharing)
  );

create policy "own plans" on plans for all
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "linked can read plans" on plans for select
  using (harbour_linked((select auth.uid()), user_id));

-- A personal note is for exactly one person; a shared one for everyone linked.
create policy "own notes" on notes for all
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "notes addressed to me" on notes for select
  using (
    case when scope = 'personal'
      then audience_id = (select auth.uid())
      else harbour_linked((select auth.uid()), user_id)
    end
  );

-- The seed rule, and the reason this table is worth its own policy: the
-- recipient cannot see the row -- not the flower, not the text, not that it
-- exists -- until the moment it opens.
create policy "seeds you planted" on seeds for all
  using ((select auth.uid()) = from_id) with check ((select auth.uid()) = from_id);
create policy "seeds that have opened for me" on seeds for select
  using ((select auth.uid()) = to_id and bloom_at <= now());

create policy "messages in my threads" on messages for select
  using ((select auth.uid()) in (from_id, to_id));
create policy "send my own messages" on messages for insert
  with check ((select auth.uid()) = from_id and harbour_linked((select auth.uid()), to_id));
-- Either side may like a message; only the sender may delete one.
create policy "update messages in my threads" on messages for update
  using ((select auth.uid()) in (from_id, to_id)) with check ((select auth.uid()) in (from_id, to_id));
create policy "delete my own messages" on messages for delete
  using ((select auth.uid()) = from_id);

create policy "own snaps" on snaps for all
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "linked can read snaps" on snaps for select
  using (harbour_linked((select auth.uid()), user_id));

create policy "own moments" on moments for all
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

create policy "own puzzle results" on puzzle_results for all
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "linked can read puzzle results" on puzzle_results for select
  using (harbour_linked((select auth.uid()), user_id));

create policy "own daily answer" on daily_answers for all
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy "linked can read daily answers" on daily_answers for select
  using (harbour_linked((select auth.uid()), user_id));

-- -------------------------------------------------------------- invites
-- A code somebody can read down a phone line without spelling it out: three
-- letters that cannot be mistaken for each other, then four digits.

create function harbour_new_invite_code() returns text
language plpgsql volatile as $$
declare
  letters constant text := 'ACDEFGHJKLMNPRTUVWXY';
  code text;
begin
  loop
    code := substr(letters, 1 + floor(random() * 20)::int, 1)
         || substr(letters, 1 + floor(random() * 20)::int, 1)
         || substr(letters, 1 + floor(random() * 20)::int, 1)
         || '-' || lpad((1000 + floor(random() * 9000))::int::text, 4, '0');
    exit when not exists (select 1 from profiles where invite_code = code);
  end loop;
  return code;
end;
$$;

-- Joining somebody. Writes BOTH contact rows in one transaction, because a
-- half-made link is exactly the state harbour_linked() is designed to reject
-- and there is no screen anywhere that could repair it.
create function redeem_invite(code text, my_label text default null)
returns uuid
language plpgsql volatile security definer set search_path = public as $$
declare
  me    uuid := auth.uid();
  host  profiles;
begin
  if me is null then
    raise exception 'not signed in' using errcode = '28000';
  end if;

  select * into host from profiles p where p.invite_code = upper(trim(code));
  if host is null then
    raise exception 'that code does not belong to anybody' using errcode = 'P0002';
  end if;
  if host.id = me then
    raise exception 'that is your own code' using errcode = 'P0001';
  end if;

  insert into contacts (user_id, linked_user_id, label)
    values (me, host.id, coalesce(host.display_name, 'Them'))
    on conflict (user_id, linked_user_id) do update set label = excluded.label;

  insert into contacts (user_id, linked_user_id, label)
    values (host.id, me, coalesce(my_label, (select display_name from profiles where id = me), 'Them'))
    on conflict (user_id, linked_user_id) do update set label = excluded.label;

  return host.id;
end;
$$;

revoke all on function redeem_invite(text, text) from public;
grant execute on function redeem_invite(text, text) to authenticated;

-- ------------------------------------------------------------- triggers
-- A new account gets a profile and a settings row, so the app never has to
-- handle a missing-settings state on first run.

create function handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, display_name, invite_code)
    values (new.id,
            coalesce(new.raw_user_meta_data ->> 'display_name', ''),
            harbour_new_invite_code());
  insert into user_settings (user_id) values (new.id);
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function handle_new_user();

create function touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

create trigger profiles_touch      before update on profiles
  for each row execute function touch_updated_at();
create trigger user_settings_touch before update on user_settings
  for each row execute function touch_updated_at();
